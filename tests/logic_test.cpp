// Host-side test of the omlet_evaluate lambda in omlet-fan.yaml, with stub types.
// Run tests/run.sh (needs esphome and g++).
#include <cmath>
#include <optional>
#include <cstdio>
#include <cassert>
#include <cstdint>
namespace esphome {
template<typename T> using optional = std::optional<T>;
namespace select { struct Select { optional<size_t> idx; optional<size_t> active_index() const { return idx; } }; }
namespace datetime { struct TimeEntity { uint8_t hour{0}, minute{0}; }; }
namespace fan {
struct Fan; struct FanCall { Fan *f; bool st; int sp{-1};
  FanCall &set_speed(int s){sp=s;return *this;} void perform(); };
struct Fan { bool state{false}; int speed{0}; int calls{0};
  FanCall turn_on(){return {this,true};} FanCall turn_off(){return {this,false};} };
void FanCall::perform(){ f->state=st; if(sp>=0) f->speed=sp; f->calls++; }
}
}  // namespace esphome
using namespace esphome;
struct ESPTime { int hour{0}, minute{0}; bool valid{true}; bool is_valid() const {return valid;} };
struct Clock { ESPTime t; ESPTime now(){return t;} };
struct Num { float state; };
select::Select *omlet_mode, *omlet_thermostat_speed, *omlet_window1_speed,*omlet_window2_speed,*omlet_window3_speed,*omlet_window4_speed;
datetime::TimeEntity *omlet_window1_on,*omlet_window1_off,*omlet_window2_on,*omlet_window2_off,*omlet_window3_on,*omlet_window3_off,*omlet_window4_on,*omlet_window4_off;
fan::Fan *omlet_fan; Clock *omlet_ha_time,*omlet_sntp_time; Num *omlet_temp_on,*omlet_temp_off,*omlet_temperature;
using namespace fan;
void evaluate() {
#include "body.inc"  // generated by tests/run.sh from omlet-fan.yaml
}
int main(){
  select::Select mode{1}, ts{1}, s1{0}, s2{2}, s3{2}, s4{2};
  datetime::TimeEntity w[8];
  Fan f; Clock ha, sn; Num on{25}, off{23}, temp{NAN};
  omlet_mode=&mode; omlet_thermostat_speed=&ts; omlet_window1_speed=&s1; omlet_window2_speed=&s2; omlet_window3_speed=&s3; omlet_window4_speed=&s4;
  omlet_window1_on=&w[0];omlet_window1_off=&w[1];omlet_window2_on=&w[2];omlet_window2_off=&w[3];omlet_window3_on=&w[4];omlet_window3_off=&w[5];omlet_window4_on=&w[6];omlet_window4_off=&w[7];
  omlet_fan=&f; omlet_ha_time=&ha; omlet_sntp_time=&sn; omlet_temp_on=&on; omlet_temp_off=&off; omlet_temperature=&temp;
  // Thermostatic
  mode.idx=2; f.state=false;
  temp.state=24; evaluate(); assert(!f.state);
  temp.state=25; evaluate(); assert(f.state && f.speed==2);
  temp.state=23.5; evaluate(); assert(f.state);
  temp.state=22.9; evaluate(); assert(!f.state);
  temp.state=-5; evaluate(); assert(!f.state);   // stock bug would switch on here
  // Manual: untouched
  mode.idx=0; f.state=true; f.speed=1; temp.state=0; evaluate(); assert(f.state && f.speed==1);
  // Time: all windows disabled -> off
  mode.idx=1; ha.t={12,0}; evaluate(); assert(!f.state);
  // window1 22:00-06:00 low
  w[0]={22,0}; w[1]={6,0};
  ha.t={23,0}; evaluate(); assert(f.state && f.speed==1);
  ha.t={3,0};  evaluate(); assert(f.state);       // stock bug would be off here
  ha.t={6,0};  evaluate(); assert(!f.state);
  // window2 10:00-11:30 high, HA clock invalid -> sntp
  w[2]={10,0}; w[3]={11,30}; ha.t.valid=false; sn.t={11,29}; evaluate(); assert(f.state && f.speed==3);
  sn.t={11,30}; evaluate(); assert(!f.state);
  sn.t.valid=false; f.state=true; evaluate(); assert(f.state); // no clock -> no change
  puts("all tests passed");
}
